import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
async function walk(dir) {
 const entries = await readdir(new URL(dir, root), {withFileTypes:true});
 return (await Promise.all(entries.map(e => e.isDirectory() ? walk(dir+e.name+'/') : dir+e.name))).flat();
}
const files = ['index.html','manifest.webmanifest', ...(await Promise.all(['senzai-kk02-pilot/','senzai-kk02/','workshop/','icons/','vendor/three/','assets/senzai-kk02/'].map(walk))).flat()]
 .filter(p=>!p.endsWith('lod0.glb')&&!p.endsWith('lod2.glb')).sort();
const digest=createHash('sha256');for(const p of files){digest.update(p);digest.update(await readFile(new URL(p,root)));}
const version=digest.digest('hex').slice(0,16);
const source=`// Generated by node tools/build-sw.mjs. Each release is an atomic offline shell.
const VERSION = '${version}';
const PREFIX = 'senzai:' + new URL(self.registration.scope).pathname + ':';
const CACHE = PREFIX + VERSION;
const FILES = ${JSON.stringify(files,null,2)};
self.addEventListener('install', event => {
 event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES.map(path => new Request(new URL(path,self.registration.scope),{cache:'reload'})))));
});
self.addEventListener('activate', event => {
 event.waitUntil((async()=>{for(const key of await caches.keys()) if(key.startsWith(PREFIX)&&key!==CACHE) await caches.delete(key);await self.clients.claim();})());
});
self.addEventListener('message', event => { if(event.data?.type==='ACTIVATE_UPDATE') self.skipWaiting(); });
self.addEventListener('fetch', event => {
 const url=new URL(event.request.url),scope=new URL(self.registration.scope);
 if(event.request.method!=='GET'||url.origin!==scope.origin||!url.pathname.startsWith(scope.pathname)) return;
 url.search='';url.hash='';if(url.pathname.endsWith('/'))url.pathname+='index.html';
 event.respondWith((async()=>{
  const cache=await caches.open(CACHE),saved=await cache.match(url.href);
  if(saved)return saved;
  const response=await fetch(event.request);
  if(response.ok&&response.type!=='opaque')event.waitUntil(cache.put(url.href,response.clone()));
  return response;
 })());
});
`;
if(process.argv.includes('--check')) {
 if(await readFile(new URL('sw.js',root),'utf8')!==source)throw Error('Offline shell is stale: run node tools/build-sw.mjs');
 console.log(`Offline shell current: ${files.length} files, version ${version}`);
} else {await writeFile(new URL('sw.js',root),source);console.log(`Built offline shell: ${files.length} files, version ${version}`);}
